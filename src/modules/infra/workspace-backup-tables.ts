/** Normalize PostgreSQL JSON and timestamps for the dialect-neutral SQL restore. */
export function workspaceBackupValue(value: unknown): unknown {
  if (value instanceof Date) return value.toISOString();
  if (value !== null && typeof value === 'object') return JSON.stringify(value);
  return value ?? null;
}
